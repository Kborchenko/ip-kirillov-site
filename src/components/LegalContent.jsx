export default function LegalContent({ slug }) {
  const scope = [candidateConsent, employerConsent].find(doc => doc.slug === slug);
  if (scope) return <ConsentDocument scope={scope}/>;
  const Content = { "personal-data": PersonalDataPolicy, privacy: Privacy, cookies: Cookies }[slug];
  return <Content/>;
}
